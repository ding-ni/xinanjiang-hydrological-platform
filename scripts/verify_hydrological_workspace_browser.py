"""Browser acceptance for the hydrological task workspace; isolated server only."""
import argparse
import json
import sys
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
sys.stdout.reconfigure(encoding='utf-8')
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--url',default='http://127.0.0.1:18898')
parser.add_argument('--output',default='开发产物/hydrological-workspace-browser')
parser.add_argument('--inspect',action='store_true')
parser.add_argument('--page',default='/calibration')
args=parser.parse_args()
output=Path(args.output).resolve();output.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    context=browser.new_context(viewport={'width':1366,'height':768})
    page=context.new_page();errors=[]
    page.on('pageerror',lambda error:(errors.append(str(error)),print('PAGE_ERROR',str(error),flush=True)))
    def get(path):
        answer=context.request.get(args.url+'/api/model/'+path,timeout=60000)
        assert answer.ok,answer.text()
        return answer.json()
    page.goto(args.url+'/#'+args.page);page.wait_for_load_state('networkidle')
    if args.inspect:
        print(page.locator('body').inner_text());page.screenshot(path=str(output/'inspect.png'),full_page=True);browser.close();raise SystemExit
    expect(page.get_by_role('heading',name='我的率定方案')).to_be_visible()
    assert not page.locator('.sidebar').get_by_text('进阶诊断',exact=True).count()
    rows=get('model-schemes')['schemes']
    delivered=next(row for row in rows if row.get('origin')=='同事交付' and not row.get('configurationPending'))
    original=get('model-schemes/'+delivered['id'])
    page.locator('[data-scheme-id="'+delivered['id']+'"]').click()
    expect(page.locator('.scheme-heading h1')).to_have_text(delivered['name'])
    expect(page.locator('.flood-panel .panel-heading')).to_contain_text('洪水目录 226 场')
    assert not page.get_by_text('方案原始输入与处理记录',exact=False).count()
    page.locator('.flood-process').last.click()
    assert get('model-schemes/'+delivered['id'])['draftRevision']==original['draftRevision']
    page.get_by_role('button',name='编辑方案',exact=True).click()
    page.locator('.purpose-select').first.select_option('未使用')
    page.wait_for_timeout(700)
    page.get_by_role('button',name='放弃修改',exact=True).click()
    expect(page.locator('.revision-label')).to_contain_text('查看')
    assert get('model-schemes/'+delivered['id'])['calculationDraft']==original['calculationDraft']
    page.get_by_role('button',name='编辑方案',exact=True).click()
    page.get_by_role('button',name='率定设置',exact=True).click()
    expect(page.locator('.scientific-conditions select').last).to_be_visible(timeout=60000)
    expect(page.locator('#reference-parameters')).to_be_visible()
    assert not page.get_by_text('初始参数保存值',exact=True).count()
    page.screenshot(path=str(output/'settings-1366.png'),full_page=True)
    page.get_by_role('button',name='完成',exact=True).click()
    page.get_by_role('button',name='人工试调',exact=True).click()
    page.locator('.parameter-kind').get_by_role('button',name='河道汇流',exact=True).click()
    expect(page.locator('.parameter-panel').get_by_label('查看河段参数')).to_be_visible()
    expect(page.locator('.parameter-panel .param-row')).to_have_count(2)
    page.screenshot(path=str(output/'manual-1366.png'),full_page=True)
    page.get_by_role('button',name='放弃修改',exact=True).click()
    expect(page.locator('.revision-label')).to_contain_text('查看')
    page.wait_for_timeout(500)
    page.goto(args.url+'/#/realtime');page.wait_for_load_state('networkidle')
    if not page.locator('.replay-mode select').count():
        page.screenshot(path=str(output/'navigation-failure.png'),full_page=True)
        print(page.locator('body').inner_text(),flush=True)
    page.locator('.replay-mode select').select_option('event')
    page.locator('.replay-controls label').filter(has_text='年份').locator('select').select_option('1988')
    expect(page.locator('.event-list')).to_be_enabled(timeout=60000)
    page.locator('.event-list').select_option('xf-31880808')
    expect(page.locator('.replay-window')).to_contain_text('1988-08-08',timeout=60000)
    expect(page.locator('.observed-process')).to_be_visible()
    page.get_by_label('降雨过程测站',exact=True).select_option('70115800')
    expect(page.locator('.rain-total')).to_contain_text('39.3 mm')
    page.locator('.time-picker input').fill('1988-08-08T07:00')
    page.locator('.time-picker input').dispatch_event('change')
    expect(page.locator('.metric').filter(has_text='本小时流域面雨量')).to_contain_text('3.5 mm')
    expect(page.locator('.observed-process .chart-host canvas')).to_have_count(1)
    for width,height in [(1366,768),(1920,1080)]:
        page.set_viewport_size({'width':width,'height':height})
        page.screenshot(path=str(output/f'rain1988-{width}.png'),full_page=True)
    page.locator('.replay-controls label').filter(has_text='年份').locator('select').select_option('2007')
    page.locator('.event-list').select_option('xf-31070314')
    expect(page.locator('.replay-window')).to_contain_text('2007-03-14',timeout=60000)
    expect(page.locator('.observed-process')).to_be_visible()
    page.goto(args.url+'/#/data');page.wait_for_load_state('networkidle')
    assert not page.get_by_role('button',name='入库记录',exact=True).count()
    page.get_by_role('button',name='洪水目录',exact=True).click()
    expect(page.get_by_role('link',name='带入模拟').first).to_be_visible()
    page.goto(args.url+'/#/config');page.wait_for_load_state('networkidle')
    page.get_by_role('button',name='河网与汇流',exact=True).click()
    expect(page.get_by_role('button',name='保存新方案默认值')).to_be_visible(timeout=60000)
    assert not page.get_by_text('已登记汇流版本',exact=True).count()
    page.screenshot(path=str(output/'routing-defaults-1920.png'),full_page=True)
    page.goto(args.url+'/#/archive');page.wait_for_load_state('networkidle')
    expect(page.get_by_role('button',name='我的成果',exact=True)).to_be_visible()
    expect(page.get_by_role('button',name='最近计算',exact=True)).to_be_visible()
    assert not errors,errors
    (output/'report.json').write_text(json.dumps({'errors':errors,'schemeId':delivered['id'],'rain1988':{'stationPeak':20.3,'stationTotal':39.3,'arealFirstHour':3.498676168920034}},ensure_ascii=False,indent=2),encoding='utf-8')
    print('HYDROLOGICAL_BROWSER_ACCEPTANCE_OK',flush=True)
    browser.close()
